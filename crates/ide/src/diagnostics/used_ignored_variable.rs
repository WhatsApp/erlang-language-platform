//! Lint: used_ignored_variable
//!
//! Return a diagnostic when a variable whose name starts with `_`, which by
//! convention marks it as ignored, is used after being bound, as in
//! `f(_X) -> _X + 1`. The compiler does not warn about unused variables with
//! such names, so the convention hides real mistakes and misleads readers.

use std::borrow::Cow;

use elp_ide_db::DiagnosticCode;
use elp_ide_db::elp_base_db::FileId;
use elp_ide_db::elp_base_db::FileRange;
use elp_syntax::TextRange;
use fxhash::FxHashSet;
use hir::AnyExpr;
use hir::AnyExprId;
use hir::Expr;
use hir::FunctionDef;
use hir::InFunctionClauseBody;
use hir::Pat;
use hir::Strategy;
use hir::Var;
use hir::fold::MacroStrategy;
use hir::fold::ParenStrategy;

use crate::diagnostics::GenericLinter;
use crate::diagnostics::GenericLinterMatchContext;
use crate::diagnostics::Linter;
use crate::diagnostics::LinterContext;

pub(crate) struct UsedIgnoredVariableLinter;

impl Linter for UsedIgnoredVariableLinter {
    fn id(&self) -> DiagnosticCode {
        DiagnosticCode::UsedIgnoredVariable
    }

    fn description(&self) -> &'static str {
        "A variable marked as ignored is used."
    }
}

#[derive(Debug, Clone)]
pub(crate) struct Context {
    name: String,
}

const STRATEGY: Strategy = Strategy {
    macros: MacroStrategy::ExpandButIncludeMacroCall,
    parens: ParenStrategy::InvisibleParens,
};

impl GenericLinter for UsedIgnoredVariableLinter {
    type Context = Context;

    fn matches(&self, ctx: &LinterContext) -> Option<Vec<GenericLinterMatchContext<Context>>> {
        let sema = ctx.sema;
        let file_id = ctx.file_id;
        let mut res = Vec::new();
        sema.for_each_function(file_id, |def| {
            let def_fb = def.in_function_body(sema, def);
            for (clause_id, clause) in def_fb.clauses() {
                // A clause generated by a top-level macro call is all macro.
                if clause.from_macro.is_some() {
                    continue;
                }
                let in_clause = def_fb.in_clause(clause_id);
                check_clause(file_id, in_clause, &mut res);
            }
        });
        res.sort_by_key(|m| m.range.range.start());
        Some(res)
    }

    fn match_description(&self, context: &Context) -> Cow<'_, str> {
        Cow::Owned(format!(
            "Variable `{}` is used, but its leading `_` marks it as ignored.",
            context.name
        ))
    }
}

pub(crate) static LINTER: UsedIgnoredVariableLinter = UsedIgnoredVariableLinter;

fn check_clause(
    file_id: FileId,
    in_clause: &InFunctionClauseBody<&FunctionDef>,
    res: &mut Vec<GenericLinterMatchContext<Context>>,
) {
    let resolver = in_clause.resolver();
    let mut uses: Vec<(Var, TextRange)> = Vec::new();
    in_clause.fold_clause(STRATEGY, (), &mut |_acc, fold_ctx| {
        // Whether a macro uses an argument can depend on the macros defined at
        // compile time, as with `-ifdef(TEST)`, so macro arguments are skipped.
        if fold_ctx.in_macro.is_some() {
            return;
        }
        let var = match (fold_ctx.item, fold_ctx.item_id) {
            (AnyExpr::Expr(Expr::Var(var)), _) => var,
            // A pattern variable that is already bound matches its value, so
            // it is a use.
            (AnyExpr::Pat(Pat::Var(var)), AnyExprId::Pat(pat_id))
                if resolver
                    .resolve_pat_id(&var, pat_id)
                    .is_some_and(|defs| !defs.contains(&pat_id)) =>
            {
                var
            }
            _ => return,
        };
        if var.is_underscore_prefixed()
            && !var.is_anonymous()
            && !var.is_double_underscore_prefixed()
            && let Some(range) = in_clause.range_for_any(fold_ctx.item_id)
        {
            uses.push((var, range.range));
        }
    });
    uses.sort_by_key(|(_, range)| range.start());
    let mut reported = FxHashSet::default();
    res.extend(
        uses.into_iter()
            .filter(|(var, _)| reported.insert(*var))
            .map(|(var, range)| GenericLinterMatchContext {
                range: FileRange { file_id, range },
                context: Context {
                    name: var.as_string(),
                },
            }),
    );
}

#[cfg(test)]
mod tests {
    use elp_ide_db::DiagnosticCode;

    use crate::diagnostics::DiagnosticsConfig;
    use crate::tests::check_diagnostics_with_config;

    fn config() -> DiagnosticsConfig {
        DiagnosticsConfig::default().disable(DiagnosticCode::UndefinedFunction)
    }

    #[track_caller]
    fn check_diagnostics(fixture: &str) {
        check_diagnostics_with_config(config(), fixture)
    }

    #[test]
    fn used_ignored_variables() {
        check_diagnostics(
            r#"
            //- /src/main.erl
            -module(main).
            -export([f/2]).
            f(_X, Y) when _X > 0 ->
            %%            ^^ warning: W0095: Variable `_X` is used, but its leading `_` marks it as ignored.
            %%             | 💡 <suppression>
                {_Z, _} = Y,
                [_X, _Z, _X];
            %%       ^^ warning: W0095: Variable `_Z` is used, but its leading `_` marks it as ignored.
            %%        | 💡 <suppression>
            f(_, _Y) ->
                _Y.
            %%  ^^ warning: W0095: Variable `_Y` is used, but its leading `_` marks it as ignored.
            %%   | 💡 <suppression>
            "#,
        );
    }

    #[test]
    fn ignores_unused_and_macro_variables() {
        check_diagnostics(
            r#"
            //- /src/main.erl
            -module(main).
            -export([f/1]).
            -define(SWAP(A), begin {_A, _B} = A, {_B, _A} end).
            -define(ID(A), A).
            f(_X) ->
                {_Y, _} = ?SWAP({1, 2}),
                __Injected = ?ID(ok),
                __Injected.
            "#,
        );
    }

    #[test]
    fn ignores_macro_arguments() {
        check_diagnostics(
            r#"
            //- /src/main.erl
            -module(main).
            -export([f/1, g/1]).
            -define(ID(A), A).
            -ifdef(TEST).
            -define(LOG(Msg), io:format("~p", [Msg])).
            -else.
            -define(LOG(Msg), ok).
            -endif.
            f(_X) -> ?ID(_X).
            g(_X) -> ?LOG(_X).
            "#,
        );
    }

    #[test]
    fn ignores_macro_generated_clauses() {
        check_diagnostics(
            r#"
            //- /src/main.erl
            -module(main).
            -export([foo/1]).
            -define(GEN, foo(_X) -> _X).
            ?GEN.
            "#,
        );
    }

    #[test]
    fn pattern_macro_argument() {
        check_diagnostics(
            r#"
            //- /src/main.erl
            -module(main).
            -export([f/1, g/1]).
            -define(ID(A), A).
            f(?ID(_X)) -> _X.
            %%            ^^ warning: W0095: Variable `_X` is used, but its leading `_` marks it as ignored.
            %%             | 💡 <suppression>
            g(?ID(_Y)) -> ok.
            "#,
        );
    }

    #[test]
    fn bound_variable_in_pattern() {
        check_diagnostics(
            r#"
            //- /src/main.erl
            -module(main).
            -export([f/2, g/2, h/1]).
            -define(ID(A), A).
            f(_X, Y) ->
                case Y of
                    _X -> ok;
            %%      ^^ warning: W0095: Variable `_X` is used, but its leading `_` marks it as ignored.
            %%       | 💡 <suppression>
                    _ -> error
                end.
            g(_X, Y) ->
                case Y of
                    ?ID(_X) -> ok;
                    _ -> error
                end.
            h(Y) ->
                case Y of
                    {_A} -> ok;
                    [_A] -> ok
                end.
            "#,
        );
    }

    #[test]
    fn bound_variable_in_pattern_in_macro_argument() {
        check_diagnostics(
            r#"
            //- /src/main.erl
            -module(main).
            -export([f/2, g/1, h/1]).
            -define(ID(A), A).
            -define(WRAP(E), (fun() -> E end)()).
            f(_X, Y) ->
                ?ID(case Y of
                        {_X} -> ok;
                        _ -> error
                    end).
            g(Y) ->
                ?ID(case Y of
                        {_A} -> ok;
                        [_A] -> ok
                    end).
            h(Y) ->
                ?WRAP(case Y of {_B} -> ok end),
                ?WRAP(case Y of {_B} -> ok end).
            "#,
        );
    }

    #[test]
    fn rebinding_in_separate_funs() {
        check_diagnostics(
            r#"
            //- /src/main.erl
            -module(main).
            -export([f/0, g/0]).
            -define(WRAP(E), (fun() -> E end)()).
            f() -> (fun() -> _A = 1 end)(), (fun() -> _A = 2 end)().
            g() -> ?WRAP(_B = 1), ?WRAP(_B = 2).
            "#,
        );
    }

    #[test]
    fn pattern_in_macro_argument() {
        check_diagnostics(
            r#"
            //- /src/main.erl
            -module(main).
            -export([f/1]).
            -define(MATCH(P, E), case E of P -> ok end).
            f(X) -> ?MATCH({_A, _}, X).
            "#,
        );
    }
}
